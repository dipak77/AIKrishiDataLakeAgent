"""Train + evaluate the NLU models (V5-F) against the heuristic router.

Usage:
    python scripts/eval_nlu.py              # train, print accuracy + samples
    python scripts/eval_nlu.py --retrain    # retrain and persist the model file
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from reasoning.nlu import (  # noqa: E402
    EntityTagger,
    IntentClassifier,
    build_intent_examples,
    build_ner_examples,
    extract_entities,
    train_models,
)

# Held-out labeled examples (not generated by the training-data builder).
EVAL_SET: list[tuple[str, str]] = [
    ("my tomato plant has brown spots and wilting leaves", "diagnosis"),
    ("black spots appeared on tomato", "diagnosis"),
    ("control of stem borer in rice", "diagnosis"),
    ("how much urea and dap should I apply to tomato", "fertilizer"),
    ("npk dose for maize", "fertilizer"),
    ("today onion rate in lasalgaon mandi", "mandi_price"),
    ("what is the bhav of soybean", "mandi_price"),
    ("will it rain in Nagpur tomorrow", "weather"),
    ("temperature forecast for Pune", "weather"),
    ("best month to sow wheat", "crop_planning"),
    ("when should I plant paddy in Punjab", "crop_planning"),
    ("package of practices for rice cultivation", "evidence"),
    ("research on drip irrigation", "evidence"),
    ("hello there", "general"),
    ("धान में काला धब्बा", "diagnosis"),
    ("टोमॅटोवर काळे डाग आहेत", "diagnosis"),
    ("தக்காளியில் கருப்பு புள்ளிகள்", "diagnosis"),
    ("ధర ఎంత", "mandi_price"),
    ("बारिश कब होगी", "weather"),
]


def _ent(tagger: EntityTagger, q: str) -> str:
    ents = extract_entities(tagger, q)
    crop = ents["crop"]["crop_id"] if ents["crop"] else "-"
    loc = ents["district"] or ents["state"] or "-"
    sym = ",".join(ents["symptoms"]) or "-"
    return f"crop={crop} loc={loc} sym={sym}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train + evaluate NLU (V5-F)")
    parser.add_argument("--retrain", action="store_true", help="retrain and persist the model file")
    parser.add_argument("--verbose", "-v", action="store_true")
    args = parser.parse_args(argv)

    model = train_models()
    clf: IntentClassifier = model.intent
    tagger: EntityTagger = model.tagger

    examples = build_intent_examples()
    train_acc = clf.accuracy(examples)
    print(f"intent model: {len(examples)} training examples, train acc = {train_acc:.3f}")

    # trained vs heuristic on the held-out set
    from reasoning.assistant import classify_intent as heuristic

    correct_t = correct_h = 0
    for q, want in EVAL_SET:
        got_t = clf.predict(q)[0]
        got_h = heuristic(q)[0]
        correct_t += got_t == want
        correct_h += got_h == want
        if args.verbose:
            conf = clf.predict(q)[2]
            print(f"  {q!r:48} trained={got_t:13} (conf {conf:.2f}) heuristic={got_h:13} want={want}")
    print(f"held-out eval ({len(EVAL_SET)}): trained = {correct_t}/{len(EVAL_SET)}, "
          f"heuristic = {correct_h}/{len(EVAL_SET)}")

    print("\nentity extraction samples:")
    for q in [
        "tomato has black spots on leaves",
        "weather in Pune",
        "when to sow wheat in Punjab",
        "टोमॅटोवर काळे डाग आहेत",
        "tomatoes have brown patches",
    ]:
        print(f"  {q!r:40} -> {_ent(tagger, q)}")

    if args.retrain:
        from reasoning.nlu import _serialize_model, MODEL_PATH, ensure_dir

        ensure_dir(MODEL_PATH.parent)
        MODEL_PATH.write_text(
            __import__("json").dumps(_serialize_model(model), ensure_ascii=False),
            encoding="utf-8",
        )
        print(f"\nmodel persisted -> {MODEL_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
